import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(root, 'src/app/features/search/data/clinical-source.json');
const outputPath = resolve(root, 'src/app/features/search/clinical-index.generated.ts');

const source = JSON.parse(await readFile(sourcePath, 'utf8'));

const painPrefixes = ['dolor', 'dolor de', 'dolor en', 'molestia', 'molestia en'];

const generatedPainEntries = source.painLocations.flatMap((entry) =>
  entry.locations.map((location) => ({
    id: `${entry.id}-${slug(location)}`,
    system: entry.system,
    medical: entry.medical,
    synonyms: [...new Set(painPrefixes.map((prefix) => `${prefix} ${location}`))],
    activeIngredients: entry.activeIngredients,
    confidence: entry.confidence,
  })),
);

const generatedEntries = dedupeEntries([...source.entries, ...generatedPainEntries]);
const redFlags = dedupeRedFlags(source.redFlags);

const content = `// Auto-generated by tools/build-clinical-index.mjs. Do not edit by hand.
// Source: src/app/features/search/data/clinical-source.json

import type { ClinicalKnowledgeEntry, RedFlagRule } from './clinical-knowledge';

export const CLINICAL_INDEX_VERSION = ${JSON.stringify(source.version)};

export const GENERATED_CLINICAL_KNOWLEDGE: ClinicalKnowledgeEntry[] = ${JSON.stringify(
  generatedEntries,
  null,
  2,
)};

export const GENERATED_RED_FLAG_RULES: RedFlagRule[] = ${JSON.stringify(redFlags, null, 2)};
`;

await writeFile(outputPath, content, 'utf8');

console.log(
  `Generated ${generatedEntries.length} clinical entries and ${redFlags.length} red-flag rules.`,
);

function dedupeEntries(entries) {
  const byId = new Map();

  for (const entry of entries) {
    byId.set(entry.id, {
      ...entry,
      synonyms: [...new Set(entry.synonyms.map((synonym) => synonym.trim()).filter(Boolean))],
      activeIngredients: [
        ...new Set(entry.activeIngredients.map((ingredient) => ingredient.trim()).filter(Boolean)),
      ],
    });
  }

  return [...byId.values()].sort((a, b) => a.id.localeCompare(b.id));
}

function dedupeRedFlags(rules) {
  const byLabel = new Map();

  for (const rule of rules) {
    const existing = byLabel.get(rule.label);
    byLabel.set(rule.label, {
      label: rule.label,
      terms: [...new Set([...(existing?.terms ?? []), ...rule.terms])],
    });
  }

  return [...byLabel.values()].sort((a, b) => a.label.localeCompare(b.label));
}

function slug(value) {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}
